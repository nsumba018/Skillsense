"""
Run the Two-Stage forecast pipeline from within Django.

This is the Django-integrated version of models/phase2d_final_model.py.
It reads historical data from the database (seeded from Dataset A), reuses the
trained LightGBM trend model (Stage 1), corrects it against Dataset B's real
current job-posting distribution (Stage 2), and stores results in
ForecastRun + RoleForecast.
"""
from pathlib import Path

import numpy as np
import pandas as pd
from django.conf import settings
from django.db import transaction

from taxonomy.models import NormalizedRole, HistoricalDemand, MacroIndicator
from predictions.models import ForecastRun, RoleForecast
from .model_loader import get_model, get_role_encoder, get_feature_list

CORRECTION_CLAMP = (0.2, 5.0)
DATASET_B_PATH = (
    Path(settings.BASE_DIR)
    / 'skillsense_job_data' / 'data' / 'current_ict' / 'ict_job_postings_v2.csv'
)


def _market_distribution():
    """Normalized role share distribution (%) from Dataset B's real postings."""
    dataset_b = pd.read_csv(DATASET_B_PATH)
    counts = dataset_b['normalized_role'].value_counts()
    return (counts / counts.sum() * 100).to_dict()


def _correction_factors(trend_shares, market_dist, roles):
    """correction = (actual + 0.5) / (predicted + 0.5), clamped to CORRECTION_CLAMP."""
    factors = {}
    for role in roles:
        t = trend_shares.get(role, 0.1)
        m = market_dist.get(role, 0)
        raw_cf = (m + 0.5) / (t + 0.5)
        factors[role] = float(np.clip(raw_cf, *CORRECTION_CLAMP))
    return factors


def run_forecast_pipeline():
    """
    Execute a full forecast run:
    1. Load data from database
    2. Run the Two-Stage model (LightGBM trend + Dataset B market correction)
    3. Store results in ForecastRun + RoleForecast

    Returns: the created ForecastRun instance
    """
    model = get_model()
    role_encoder = get_role_encoder()
    features = get_feature_list()

    roles = {r.name: r for r in NormalizedRole.objects.filter(is_emerging=False)}

    history = HistoricalDemand.objects.filter(
        year__gte=2010
    ).select_related('role').order_by('year')

    macro = {m.year: m for m in MacroIndicator.objects.all()}

    rows = []
    for hd in history:
        m = macro.get(hd.year)
        if not m:
            continue
        rows.append({
            'year': hd.year,
            'role': hd.role.name,
            'role_share_within_ict_pct': hd.role_share_within_ict_pct,
            'role_demand_index': hd.role_demand_index,
            'role_employment_proxy': hd.role_employment_proxy,
            'ict_employment_share_pct': m.ict_employment_share_pct,
            'emergence_year': hd.role.emergence_year,
        })

    df = pd.DataFrame(rows)
    if df.empty:
        raise ValueError(
            "No historical data available for forecasting. "
            "Run 'python manage.py seed_taxonomy' and 'seed_historical_data' first."
        )

    df['role_encoded'] = role_encoder.transform(df['role'])
    df['years_since_emergence'] = (df['year'] - df['emergence_year']).clip(lower=0)
    min_year, max_year = df['year'].min(), df['year'].max()
    df['trend_position'] = (df['year'] - min_year) / max(max_year - min_year, 1)
    df = df.sort_values(['role', 'year'])
    df['share_lag1'] = df.groupby('role')['role_share_within_ict_pct'].shift(1)
    df['share_change_1y'] = df.groupby('role')['role_share_within_ict_pct'].diff(1)
    df['share_change_2y'] = df.groupby('role')['role_share_within_ict_pct'].diff(2)
    df['share_accel'] = df.groupby('role')['share_change_1y'].diff(1)
    df['share_growth_rate'] = df['share_change_1y'] / df['role_share_within_ict_pct'].clip(lower=0.01)

    latest_year = df['year'].max()
    latest_data = df[df['year'] == latest_year].copy()
    all_roles = list(latest_data['role'])

    X_latest = latest_data[features].fillna(0)
    trend_latest_raw = np.clip(model.predict(X_latest), 0, None)
    trend_latest = dict(zip(all_roles, trend_latest_raw / trend_latest_raw.sum() * 100))

    market_dist = _market_distribution()
    correction_factors = _correction_factors(trend_latest, market_dist, all_roles)

    current_shares = dict(zip(latest_data['role'], latest_data['role_share_within_ict_pct']))

    horizons = [('6m', 0.5), ('1y', 1), ('2y', 2)]

    with transaction.atomic():
        forecast_run = ForecastRun.objects.create(
            model_version='two_stage_v1',
            accuracy_spearman=0.9898,
            accuracy_pearson=0.9946,
            accuracy_r2=0.9580,
            accuracy_mae=0.3277,
            notes='Auto-generated by Django forecast pipeline (live re-run)',
        )

        for horizon_label, years_ahead in horizons:
            pred_data = latest_data.copy()
            pred_data['year'] = latest_year + years_ahead
            pred_data['trend_position'] = 1.0

            X_pred = pred_data[features].fillna(0)
            trend_preds = np.clip(model.predict(X_pred), 0, None)
            total = trend_preds.sum()
            trend_shares = dict(zip(all_roles, trend_preds / total * 100 if total > 0 else trend_preds))

            cf = correction_factors
            if horizon_label == '2y':
                cf = {r: 1.0 + (v - 1.0) * 0.7 for r, v in correction_factors.items()}

            corrected = {r: max(trend_shares.get(r, 0) * cf.get(r, 1.0), 0) for r in all_roles}
            total_corrected = sum(corrected.values())
            if total_corrected > 0:
                corrected = {r: v / total_corrected * 100 for r, v in corrected.items()}

            max_share = max(corrected.values()) if corrected else 1

            for role_name in all_roles:
                role_obj = roles.get(role_name)
                if not role_obj:
                    continue

                current_share = current_shares.get(role_name, 0)
                forecast_share = corrected[role_name]
                demand_index = (forecast_share / max_share * 100) if max_share > 0 else 0

                change = forecast_share - current_share
                if change > 0.5:
                    trend = 'growing'
                elif change < -0.5:
                    trend = 'declining'
                else:
                    trend = 'stable'

                RoleForecast.objects.create(
                    forecast_run=forecast_run,
                    role=role_obj,
                    horizon=horizon_label,
                    demand_index=round(demand_index, 2),
                    share_pct=round(forecast_share, 2),
                    employment_proxy=round(forecast_share * 1000, 0),
                    trend_direction=trend,
                )

    return forecast_run
